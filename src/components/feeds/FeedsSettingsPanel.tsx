'use client';

import { useCallback, useEffect, useId, useState } from 'react';
import Link from 'next/link';
import { useTranslations } from 'next-intl';
import { AlertTriangle, Check, CheckCircle2, Copy, Loader2, RefreshCw, ShieldCheck } from 'lucide-react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { ToggleSwitch } from '@/components/common/ToggleSwitch';
import { AppSettingsFooter } from '@/components/apps/AppSettingsFooter';
import { useStoreAppSettingsForm } from '@/components/apps/useStoreAppSettingsForm';
import { ConfirmDialog } from '@/components/importer/ImporterBits';
import { useApiError } from '@/lib/useApiError';
import { useTransientFlag } from '@/lib/useTransientFlag';
import { setCachedStoreApps, useStoreApps } from '@/lib/useStoreApps';
import type { MyStoreAppView } from '@/lib/storeApps.registry';
import {
  FEEDS_LIMITS,
  feedsApi,
  normalizeFeedsSettings,
  prepareFeedsSettings,
  sameFeedsSettings,
  type FeedProductRef,
  type FeedValidationReport,
  type FeedsSettings,
  type MyFeedsView,
} from './feeds.api';

interface FeedsSettingsPanelProps {
  app: MyStoreAppView;
  token: string;
}

function CopyUrl({ value, label }: { value: string; label: string }) {
  const t = useTranslations('creator.feeds.urls');
  const [copied, flashCopied] = useTransientFlag(1500);
  const onCopy = async () => {
    try {
      await navigator.clipboard.writeText(value);
      flashCopied();
    } catch {
      // Clipboard may be unavailable (insecure context); the value is still readable.
    }
  };
  return (
    <div className="space-y-1">
      <span className="text-xs font-medium">{label}</span>
      <div className="flex items-center gap-1.5 min-w-0">
        <code className="min-w-0 flex-1 truncate rounded border bg-zinc-50 px-2 py-1 font-mono text-xs text-zinc-800" dir="ltr">
          {value}
        </code>
        <button
          type="button"
          onClick={onCopy}
          className="inline-flex shrink-0 items-center rounded border border-zinc-200 bg-white p-1.5 text-zinc-600 hover:bg-zinc-50"
          aria-label={t('copy')}
          title={t('copy')}
        >
          {copied ? <Check className="size-3.5 text-emerald-600" /> : <Copy className="size-3.5" />}
        </button>
      </div>
    </div>
  );
}

function ProductRefList({ title, items }: { title: string; items: FeedProductRef[] }) {
  if (items.length === 0) return null;
  return (
    <div className="space-y-1">
      <p className="text-xs font-medium">{title}</p>
      <ul className="max-h-48 space-y-0.5 overflow-auto text-xs">
        {items.map((p) => (
          <li key={p.id}>
            <Link href={`/creator/products/own/${p.id}`} className="text-primary hover:underline">
              {p.title}
            </Link>
          </li>
        ))}
      </ul>
    </div>
  );
}

/**
 * Settings of the feeds app (M5.6): which feeds are on, defaults, the
 * per-market feed URLs (secret token in the path, copy + rotate) and a
 * server-side validation that reports counts and products missing gtin /
 * brand. The token is generated by the API on first read and only ever
 * changed through "Rotate".
 */
export function FeedsSettingsPanel({ app, token }: FeedsSettingsPanelProps) {
  const t = useTranslations('creator.feeds');
  const uid = useId();
  const apiError = useApiError();
  const { apps } = useStoreApps();
  const { form, update, saving, dirty, save, error, saved } = useStoreAppSettingsForm<FeedsSettings>({
    app,
    token,
    normalize: normalizeFeedsSettings,
    same: sameFeedsSettings,
    prepare: prepareFeedsSettings,
    fallbackError: t('saveFailed'),
  });

  const [view, setView] = useState<MyFeedsView | null>(null);
  const [viewError, setViewError] = useState<string | null>(null);
  const [rotateOpen, setRotateOpen] = useState(false);
  const [rotating, setRotating] = useState(false);
  const [rotateError, setRotateError] = useState<string | null>(null);
  const [validating, setValidating] = useState(false);
  const [validateMarket, setValidateMarket] = useState<string | null>(null);
  const [report, setReport] = useState<FeedValidationReport | null>(null);
  const [validateError, setValidateError] = useState<string | null>(null);

  // The API may have just generated the token: push the fresh settings into
  // the shared apps cache so the form's persisted copy (and the sidebar)
  // know it, without marking the form dirty.
  const adopt = useCallback(
    (next: MyFeedsView) => {
      setView(next);
      if (apps) {
        setCachedStoreApps(apps.map((a) => (a.key === 'feeds' ? { ...a, settings: { ...next.settings } } : a)));
      }
    },
    [apps],
  );

  useEffect(() => {
    let cancelled = false;
    feedsApi
      .settings(token)
      .then((v) => {
        if (!cancelled) adopt(v);
      })
      .catch((err) => {
        if (!cancelled) setViewError(apiError(err));
      });
    return () => {
      cancelled = true;
    };
    // Load once per mount; `adopt` only changes with the apps cache.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [token]);

  const rotate = async () => {
    setRotating(true);
    setRotateError(null);
    try {
      const next = await feedsApi.rotateToken(token);
      adopt(next);
      update('token', next.settings.token);
      setRotateOpen(false);
    } catch (err) {
      setRotateError(apiError(err));
    } finally {
      setRotating(false);
    }
  };

  const validate = async () => {
    setValidating(true);
    setValidateError(null);
    try {
      setReport(await feedsApi.validate(token, validateMarket));
    } catch (err) {
      setValidateError(apiError(err));
    } finally {
      setValidating(false);
    }
  };

  const markets = view?.urls ?? [];
  const issues = report ? report.missing_gtin.length + report.missing_brand.length : 0;

  return (
    <div className="space-y-5">
      <Card className="shadow-none">
        <CardHeader className="pb-3">
          <CardTitle className="text-sm font-semibold">{t('settings.title')}</CardTitle>
          <CardDescription>{t('settings.subtitle')}</CardDescription>
        </CardHeader>
        <CardContent className="space-y-4">
          <div className="flex items-center justify-between gap-3">
            <div>
              <Label htmlFor={`${uid}-google`} className="text-xs">{t('settings.google')}</Label>
              <p className="text-[10px] text-muted-foreground">{t('settings.googleHint')}</p>
            </div>
            <ToggleSwitch id={`${uid}-google`} checked={form.google} onChange={(v) => update('google', v)} />
          </div>
          <div className="flex items-center justify-between gap-3">
            <div>
              <Label htmlFor={`${uid}-facebook`} className="text-xs">{t('settings.facebook')}</Label>
              <p className="text-[10px] text-muted-foreground">{t('settings.facebookHint')}</p>
            </div>
            <ToggleSwitch id={`${uid}-facebook`} checked={form.facebook} onChange={(v) => update('facebook', v)} />
          </div>
          <div className="flex items-center justify-between gap-3">
            <div>
              <Label htmlFor={`${uid}-variants`} className="text-xs">{t('settings.includeVariants')}</Label>
              <p className="text-[10px] text-muted-foreground">{t('settings.includeVariantsHint')}</p>
            </div>
            <ToggleSwitch id={`${uid}-variants`} checked={form.include_variants} onChange={(v) => update('include_variants', v)} />
          </div>
          <div className="grid gap-3 sm:grid-cols-2">
            <div className="space-y-1.5">
              <Label htmlFor={`${uid}-brand`} className="text-xs">{t('settings.defaultBrand')}</Label>
              <Input
                id={`${uid}-brand`}
                className="h-8 text-sm"
                maxLength={FEEDS_LIMITS.default_brand}
                value={form.default_brand ?? ''}
                onChange={(e) => update('default_brand', e.target.value || null)}
              />
              <p className="text-[10px] text-muted-foreground">{t('settings.defaultBrandHint')}</p>
            </div>
            <div className="space-y-1.5">
              <Label htmlFor={`${uid}-shipping`} className="text-xs">{t('settings.shippingLabel')}</Label>
              <Input
                id={`${uid}-shipping`}
                className="h-8 text-sm"
                maxLength={FEEDS_LIMITS.shipping_label}
                value={form.shipping_label ?? ''}
                onChange={(e) => update('shipping_label', e.target.value || null)}
                placeholder={t('settings.shippingLabelPlaceholder')}
              />
              <p className="text-[10px] text-muted-foreground">{t('settings.shippingLabelHint')}</p>
            </div>
          </div>
          <AppSettingsFooter error={error} saved={saved} savedLabel={t('settings.saved')} saving={saving} dirty={dirty} onSave={save} />
        </CardContent>
      </Card>

      <Card className="shadow-none">
        <CardHeader className="pb-3">
          <div className="flex items-start justify-between gap-3">
            <div>
              <CardTitle className="text-sm font-semibold">{t('urls.title')}</CardTitle>
              <CardDescription>{t('urls.subtitle')}</CardDescription>
            </div>
            <Button type="button" size="sm" variant="outline" disabled={!view} onClick={() => { setRotateError(null); setRotateOpen(true); }}>
              <RefreshCw className="size-3.5" /> {t('urls.rotate')}
            </Button>
          </div>
        </CardHeader>
        <CardContent className="space-y-4">
          {viewError && <p className="text-xs text-red-600">{viewError}</p>}
          {!view && !viewError && (
            <div className="flex justify-center py-4">
              <Loader2 className="size-4 animate-spin text-muted-foreground" />
            </div>
          )}
          {markets.map((m) => (
            <div key={m.market_key ?? 'default'} className="space-y-2 rounded-md border p-3">
              <p className="text-xs font-semibold">
                {m.market_name ? `${m.market_name} (${m.market_key})` : t('urls.singleMarket')}
                <span className="ms-2 font-normal text-muted-foreground">{m.currency}</span>
              </p>
              {form.google ? <CopyUrl label={t('urls.google')} value={m.google} /> : null}
              {form.facebook ? <CopyUrl label={t('urls.facebook')} value={m.facebook} /> : null}
              {!form.google && !form.facebook && <p className="text-xs text-muted-foreground">{t('urls.allOff')}</p>}
            </div>
          ))}
          <p className="text-[10px] text-muted-foreground">{t('urls.hint')}</p>
        </CardContent>
      </Card>

      <Card className="shadow-none">
        <CardHeader className="pb-3">
          <div className="flex items-start justify-between gap-3">
            <div>
              <CardTitle className="text-sm font-semibold">{t('validate.title')}</CardTitle>
              <CardDescription>{t('validate.subtitle')}</CardDescription>
            </div>
            <div className="flex items-center gap-2">
              {markets.length > 1 && (
                <select
                  className="h-8 rounded-md border bg-white px-2 text-xs"
                  value={validateMarket ?? ''}
                  onChange={(e) => setValidateMarket(e.target.value || null)}
                  aria-label={t('validate.market')}
                >
                  {markets.map((m) => (
                    <option key={m.market_key ?? 'default'} value={m.market_key ?? ''}>
                      {m.market_name ?? t('urls.singleMarket')}
                    </option>
                  ))}
                </select>
              )}
              <Button type="button" size="sm" disabled={validating} onClick={validate}>
                {validating ? <Loader2 className="size-3.5 animate-spin" /> : <ShieldCheck className="size-3.5" />} {t('validate.run')}
              </Button>
            </div>
          </div>
        </CardHeader>
        <CardContent className="space-y-3">
          {validateError && <p className="text-xs text-red-600">{validateError}</p>}
          {!report && !validateError && <p className="text-xs text-muted-foreground">{t('validate.empty')}</p>}
          {report && (
            <>
              <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
                {[
                  ['products', report.products],
                  ['items', report.items],
                  ['excluded', report.skipped.excluded],
                  ['hidden', report.skipped.hidden_in_market],
                ].map(([key, value]) => (
                  <div key={String(key)} className="rounded-md border p-2">
                    <p className="text-[10px] uppercase tracking-wide text-muted-foreground">{t(`validate.counts.${key}`)}</p>
                    <p className="text-lg font-semibold tabular-nums">{value}</p>
                  </div>
                ))}
              </div>
              <p className="flex items-center gap-1.5 text-xs">
                {issues === 0 ? (
                  <>
                    <CheckCircle2 className="size-3.5 text-emerald-600" /> {t('validate.ok', { currency: report.currency })}
                  </>
                ) : (
                  <>
                    <AlertTriangle className="size-3.5 text-amber-600" />{' '}
                    {t('validate.issues', { gtin: report.missing_gtin.length, brand: report.missing_brand.length, bare: report.missing_identifier })}
                  </>
                )}
              </p>
              <ProductRefList title={t('validate.missingGtin')} items={report.missing_gtin} />
              <ProductRefList title={t('validate.missingBrand')} items={report.missing_brand} />
              <ProductRefList title={t('validate.excludedList')} items={report.excluded} />
            </>
          )}
        </CardContent>
      </Card>

      <ConfirmDialog
        open={rotateOpen}
        title={t('urls.rotateTitle')}
        description={t('urls.rotateBody')}
        confirmLabel={t('urls.rotate')}
        destructive
        busy={rotating}
        error={rotateError}
        onConfirm={rotate}
        onOpenChange={setRotateOpen}
      />
    </div>
  );
}
